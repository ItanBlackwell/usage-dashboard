'use strict';
// Minimal dependency-free CJS bundler. OpenCode Desktop supplies its GUI SDK.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const oldCore = fs.readFileSync(path.join(root,'src/core.cjs'),'utf8');
const accounts = fs.readFileSync(path.join(root,'src/accounts.cjs'),'utf8');
const providerModules=['provider-metrics','provider-claude','provider-kimi','provider-zai','provider-minimax','local-usage'];
const moduleVar=name=>'__'+name.replaceAll('-','_');
const inlineProviders=source=>providerModules.reduce((text,name)=>text.replaceAll("require('./"+name+".cjs')",moduleVar(name)+'.exports'),source);
const providerBundle=providerModules.map(name=>{
  const variable=moduleVar(name),source=inlineProviders(fs.readFileSync(path.join(root,'src/'+name+'.cjs'),'utf8'));
  return 'const '+variable+'={exports:{}}; (function(module,exports){\n'+source+'\n})('+variable+','+variable+'.exports);\n';
}).join('');
const gui = fs.readFileSync(path.join(root,'src/gui-entry.cjs'),'utf8');
const cache = fs.readFileSync(path.join(root,'src/cache.cjs'),'utf8');
const presentation = fs.readFileSync(path.join(root,'src/presentation.cjs'),'utf8');
const switchQueue = fs.readFileSync(path.join(root,'src/switch-queue.cjs'),'utf8');
const nativeUpdate = fs.readFileSync(path.join(root,'src/native-update-layout.cjs'),'utf8');
if (!gui.includes("const cache = require('./cache.cjs');") || !accounts.includes("const base = require('./core.cjs');") || !gui.includes("const core = require('./accounts.cjs');") || !gui.includes("const presentation = require('./presentation.cjs');") || !gui.includes("const switchQueue = require('./switch-queue.cjs');") || !gui.includes("const nativeUpdate = require('./native-update-layout.cjs');")) throw new Error('Unexpected module imports');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const sha = /^[0-9a-f]{40}$/i.test(process.env.GITHUB_SHA || '')
  ? process.env.GITHUB_SHA.toLowerCase() : 'local-build';
const banner = [
  '/*',
  ' * Usage Dashboard - generated GUI module',
  ' * Copyright (c) 2026 ItanBlackwell.',
  ' * SPDX-License-Identifier: MPL-2.0',
  ` * Version: ${pkg.version}`,
  ` * Source-Revision: ${sha}`,
  ' * Source: https://github.com/ItanBlackwell/usage-dashboard',
  ' * Generated by build.cjs; edit src/ rather than this file.',
  ' */',
].join('\n') + '\n';
const text = banner + `'use strict';\n` +
  `const __old={exports:{}}; (function(module,exports){\n${oldCore}\n})(__old,__old.exports);\n` +
  providerBundle +
  `const __accounts={exports:{}}; (function(module,exports){\n${inlineProviders(accounts).replace("const base = require('./core.cjs');",'const base = __old.exports;')}\n})(__accounts,__accounts.exports);\n` +
  `const __cache={exports:{}}; (function(module,exports){\n${inlineProviders(cache)}\n})(__cache,__cache.exports);\n` +
  `const __presentation={exports:{}}; (function(module,exports){\n${presentation}\n})(__presentation,__presentation.exports);\n` +
  `const __switchQueue={exports:{}}; (function(module,exports){\n${switchQueue}\n})(__switchQueue,__switchQueue.exports);\n` +
  `const __nativeUpdate={exports:{}}; (function(module,exports){\n${nativeUpdate}\n})(__nativeUpdate,__nativeUpdate.exports);\n` +
  gui.replace("const core = require('./accounts.cjs');",'const core = __accounts.exports;')
     .replace("const presentation = require('./presentation.cjs');",'const presentation = __presentation.exports;')
     .replace("const cache = require('./cache.cjs');","const cache = __cache.exports;")
     .replace("const switchQueue = require('./switch-queue.cjs');","const switchQueue = __switchQueue.exports;")
     .replace("const nativeUpdate = require('./native-update-layout.cjs');","const nativeUpdate = __nativeUpdate.exports;") + '\n';
fs.mkdirSync(path.join(root,'dist'),{recursive:true});
fs.writeFileSync(path.join(root,'dist/gui-experimental.cjs'),text);
console.log(`Built dist/gui-experimental.cjs (${Buffer.byteLength(text)} bytes)`);
